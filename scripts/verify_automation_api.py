"""Isolated Home Assistant and print-system API contract checks for issue #26."""
from __future__ import annotations

import os
import shutil
import subprocess
import tempfile
import time
from pathlib import Path


QA_ROOT = Path(tempfile.gettempdir()) / "puzzary-automation-api-qa"
QA_DB = QA_ROOT / "automation.sqlite"
if QA_ROOT.exists():
    shutil.rmtree(QA_ROOT)
QA_ROOT.mkdir(parents=True)

os.environ["DATABASE_URL"] = f"sqlite:///{QA_DB.as_posix()}"
os.environ["SESSION_SECRET"] = "isolated-automation-api-secret"
os.environ["UPLOAD_DIR"] = str(QA_ROOT / "uploads")
os.environ["APP_BASE_URL"] = "https://puzzary.example.test"

from playwright.sync_api import sync_playwright
from sqlalchemy import select

from app.database import Base, SessionLocal, engine
from app.main import hash_secret
from app.models import PermissionRole, Puzzle, User
from app.permissions import initialize_permissions


ADMIN_TOKEN = "automation-admin-token"
PLAYER_TOKEN = "automation-player-token"
Base.metadata.drop_all(engine)
Base.metadata.create_all(engine)
with SessionLocal() as db:
    admin = User(
        display_name="Automation Admin", is_admin=True, is_active=True,
        api_token_hash=hash_secret(ADMIN_TOKEN), api_token_prefix="automation",
    )
    db.add(admin)
    db.commit()
    initialize_permissions(db)
    player_role = db.scalar(select(PermissionRole).where(PermissionRole.name == "Player"))
    player = User(
        display_name="Print Client", is_active=True, roles=[player_role], permissions_initialized=True,
        api_token_hash=hash_secret(PLAYER_TOKEN), api_token_prefix="automation",
    )
    db.add(player)
    db.commit()


BASE = "http://127.0.0.1:8808"
server = subprocess.Popen(
    ["uvicorn", "app.main:app", "--host", "127.0.0.1", "--port", "8808"],
    stdout=subprocess.DEVNULL,
    stderr=subprocess.DEVNULL,
)
try:
    with sync_playwright() as playwright:
        anonymous = playwright.request.new_context()
        admin = playwright.request.new_context(extra_http_headers={"Authorization": f"Bearer {ADMIN_TOKEN}"})
        player = playwright.request.new_context(extra_http_headers={"Authorization": f"Bearer {PLAYER_TOKEN}"})
        for _ in range(100):
            try:
                if anonymous.get(BASE + "/health").ok:
                    break
            except Exception:
                time.sleep(0.1)
        else:
            raise RuntimeError("Automation API QA server did not start")

        generated = admin.post(BASE + "/api/puzzles/generate", data={
            "puzzle_type": "takuzu",
            "difficulty": "easy",
            "seed": "automation-api-qa",
            "generation_options": {"grid_size": 4, "given_count": 6},
        })
        assert generated.ok, generated.text()
        puzzle = generated.json()
        puzzle_id = puzzle["id"]
        assert puzzle["publication_state"] == "published"
        assert puzzle["print_payload"] and "solution_payload" not in puzzle
        assert player.post(BASE + "/api/puzzles/generate", data={
            "puzzle_type": "takuzu", "difficulty": "easy",
        }).status == 403

        latest = player.get(BASE + "/api/puzzles/latest?printable=true")
        assert latest.ok and latest.json()["id"] == puzzle_id

        issue_create = admin.post(BASE + "/api/issues", data={
            "title": "Automation issue",
            "description": "Generated by isolated QA",
            "modules": [{"kind": "puzzle", "puzzle_id": puzzle_id}],
        })
        assert issue_create.status == 201, issue_create.text()
        issue_id = issue_create.json()["id"]
        published = admin.post(BASE + f"/api/issues/{issue_id}/publish")
        assert published.ok, published.text()
        assert published.json()["modules"][0]["print_payload"]

        assert anonymous.post(BASE + "/api/print/manifest", data={"latest_puzzle": True}).status == 401
        assert player.post(BASE + "/api/print/manifest", data={}).status == 422
        manifest_response = player.post(BASE + "/api/print/manifest", data={
            "puzzle_ids": [puzzle_id, puzzle_id],
            "issue_ids": [issue_id, issue_id],
            "latest_puzzle": True,
            "latest_issue": True,
        })
        assert manifest_response.ok, manifest_response.text()
        manifest = manifest_response.json()
        assert manifest["schema"] == "puzzary.print-manifest.v1" and manifest["generated_at"]
        assert len(manifest["puzzles"]) == 1 and len(manifest["issues"]) == 1
        job = manifest["puzzles"][0]
        assert job["id"] == puzzle_id and job["print_payload"] == puzzle["print_payload"]
        assert job["layout"]["render_url"] == job["render_url"]
        assert job["url"].startswith("https://puzzary.example.test/")
        assert job["pdf_url"].startswith("https://puzzary.example.test/api/")
        bundle = manifest["issues"][0]
        assert bundle["id"] == issue_id and bundle["modules"][0]["print_payload"]
        serialized = manifest_response.text()
        assert "solution_payload" not in serialized
        assert ADMIN_TOKEN not in serialized and PLAYER_TOKEN not in serialized

        selected = player.post(BASE + "/api/print/manifest", data={"puzzle_ids": [puzzle_id]})
        assert selected.ok and not selected.json()["issues"]
        assert player.post(BASE + "/api/print/manifest", data={
            "puzzle_ids": ["missing-puzzle"],
        }).status == 404

        draft = admin.post(BASE + "/api/issues", data={
            "title": "Draft automation issue",
            "modules": [{"kind": "puzzle", "puzzle_id": puzzle_id}],
        })
        assert draft.status == 201
        rejected_draft = admin.post(BASE + "/api/print/manifest", data={
            "issue_ids": [draft.json()["id"]],
        })
        assert rejected_draft.status == 422

        with SessionLocal() as db:
            db.add(Puzzle(
                id="digital-only-fixture", puzzle_type="unknown_digital", title="Digital fixture",
                theme="", difficulty="easy", prompt="", print_payload={}, play_payload={},
                solution_payload={}, puzzle_metadata={}, source="test",
            ))
            db.commit()
        not_printable = player.post(BASE + "/api/print/manifest", data={
            "puzzle_ids": ["digital-only-fixture"],
        })
        assert not_printable.status == 422

        for context in (anonymous, admin, player):
            context.dispose()
    print("Automation generation, latest selection, spoiler-free manifests, issue bundles, permissions, and generic URLs passed.")
finally:
    server.terminate()
    try:
        server.wait(timeout=10)
    except subprocess.TimeoutExpired:
        server.kill()
        server.wait()
    shutil.rmtree(QA_ROOT, ignore_errors=True)
